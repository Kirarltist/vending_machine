-- 文件：xianshi.vhd
-- 模块：xianshi（自动售货机显示模块，对应教材图 7.15 仿真图）
-- 说明：纯组合逻辑。把三路 4 位金额（价格 price、应付 need、找零 mout）
--       分别译码成 7 段显示码 I1、I2、I3。
--
--       仿真图（图 7.15）行为：
--         price / need / mout 从 0000 递增到 1111，每变一次，
--         I1 / I2 / I3 立刻输出对应的 7 段码，无时钟、无时序。
--
--       段码位的排列（由 "0000"=>"0111111" 反推）：
--         "0111111" 中"0"在最高位，对应 0 时熄灭的 g 段，
--         所以 7 位从高到低为  g f e d c b a
--         （最高位 g，最低位 a；dp 段不使用）。
--
--       段码约定：段控信号为 1 时该段点亮（共阴数码管，1 点亮）。
--                 若你的板子是共阳，把每个字面量按位取反即可。
--
--       编码表为标准七段码 0~F（十六进制）：
--         0000->0  0001->1  0010->2  0011->3  0100->4  0101->5
--         0110->6  0111->7  1000->8  1001->9  1010->A  1011->B
--         1100->C  1101->d  1110->E  1111->F
--------------------------------------------------------------------------------

LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.STD_LOGIC_UNSIGNED.ALL;

ENTITY xianshi IS
  PORT(
    price : IN  STD_LOGIC_VECTOR(3 DOWNTO 0);  -- 商品价格
    need  : IN  STD_LOGIC_VECTOR(3 DOWNTO 0);  -- 应付金额
    mout  : IN  STD_LOGIC_VECTOR(3 DOWNTO 0);  -- 找零金额
    I1    : OUT STD_LOGIC_VECTOR(6 DOWNTO 0);  -- price 的七段显示码  g f e d c b a
    I2    : OUT STD_LOGIC_VECTOR(6 DOWNTO 0);  -- need  的七段显示码
    I3    : OUT STD_LOGIC_VECTOR(6 DOWNTO 0)   -- mout  的七段显示码
  );
END xianshi;

ARCHITECTURE rtl OF xianshi IS
BEGIN

  PROCESS(price, need, mout)
  BEGIN

    ---------------------------------------------------------------------------
    -- 价格译码
    ---------------------------------------------------------------------------
    CASE price IS
      WHEN "0000" => I1 <= "0111111";   -- 0
      WHEN "0001" => I1 <= "0000110";   -- 1
      WHEN "0010" => I1 <= "1011011";   -- 2
      WHEN "0011" => I1 <= "1001111";   -- 3
      WHEN "0100" => I1 <= "1100110";   -- 4
      WHEN "0101" => I1 <= "1101101";   -- 5
      WHEN "0110" => I1 <= "1111101";   -- 6
      WHEN "0111" => I1 <= "0000111";   -- 7
      WHEN "1000" => I1 <= "1111111";   -- 8
      WHEN "1001" => I1 <= "1101111";   -- 9
      WHEN "1010" => I1 <= "1110111";   -- A
      WHEN "1011" => I1 <= "1111100";   -- b
      WHEN "1100" => I1 <= "0111001";   -- C
      WHEN "1101" => I1 <= "1011110";   -- d
      WHEN "1110" => I1 <= "1111001";   -- E
      WHEN "1111" => I1 <= "1110001";   -- F
      WHEN OTHERS => I1 <= "0000000";   -- 全灭（4 位取值已全覆盖，仅作健壮性写法）
    END CASE;

    ---------------------------------------------------------------------------
    -- 应付金额译码
    ---------------------------------------------------------------------------
    CASE need IS
      WHEN "0000" => I2 <= "0111111";   -- 0
      WHEN "0001" => I2 <= "0000110";   -- 1
      WHEN "0010" => I2 <= "1011011";   -- 2
      WHEN "0011" => I2 <= "1001111";   -- 3
      WHEN "0100" => I2 <= "1100110";   -- 4
      WHEN "0101" => I2 <= "1101101";   -- 5
      WHEN "0110" => I2 <= "1111101";   -- 6
      WHEN "0111" => I2 <= "0000111";   -- 7
      WHEN "1000" => I2 <= "1111111";   -- 8
      WHEN "1001" => I2 <= "1101111";   -- 9
      WHEN "1010" => I2 <= "1110111";   -- A
      WHEN "1011" => I2 <= "1111100";   -- b
      WHEN "1100" => I2 <= "0111001";   -- C
      WHEN "1101" => I2 <= "1011110";   -- d
      WHEN "1110" => I2 <= "1111001";   -- E
      WHEN "1111" => I2 <= "1110001";   -- F
      WHEN OTHERS => I2 <= "0000000";
    END CASE;

    ---------------------------------------------------------------------------
    -- 找零金额译码
    ---------------------------------------------------------------------------
    CASE mout IS
      WHEN "0000" => I3 <= "0111111";   -- 0
      WHEN "0001" => I3 <= "0000110";   -- 1
      WHEN "0010" => I3 <= "1011011";   -- 2
      WHEN "0011" => I3 <= "1001111";   -- 3
      WHEN "0100" => I3 <= "1100110";   -- 4
      WHEN "0101" => I3 <= "1101101";   -- 5
      WHEN "0110" => I3 <= "1111101";   -- 6
      WHEN "0111" => I3 <= "0000111";   -- 7
      WHEN "1000" => I3 <= "1111111";   -- 8
      WHEN "1001" => I3 <= "1101111";   -- 9
      WHEN "1010" => I3 <= "1110111";   -- A
      WHEN "1011" => I3 <= "1111100";   -- b
      WHEN "1100" => I3 <= "0111001";   -- C
      WHEN "1101" => I3 <= "1011110";   -- d
      WHEN "1110" => I3 <= "1111001";   -- E
      WHEN "1111" => I3 <= "1110001";   -- F
      WHEN OTHERS => I3 <= "0000000";
    END CASE;

  END PROCESS;

END rtl;
